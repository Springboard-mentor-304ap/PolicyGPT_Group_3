from pathlib import Path
import re

from openpyxl import Workbook
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter
from openpyxl.worksheet.worksheet import Worksheet

from backend.app.reports.generators import (
    format_filters,
    format_timestamp,
    report_type_label,
)
from backend.app.reports.schemas import ReportContent, ReportSection, ReportTable

TITLE_FONT = Font(bold=True, size=14, color="1F4E79")
SUBTITLE_FONT = Font(bold=True, size=12)
SECTION_FONT = Font(bold=True, size=11, color="1F4E79")
LABEL_FONT = Font(bold=True)
HEADER_FONT = Font(bold=True, color="FFFFFF")
HEADER_FILL = PatternFill("solid", fgColor="1F4E79")

THIN_BORDER = Border(
    left=Side(style="thin", color="B7C4D4"),
    right=Side(style="thin", color="B7C4D4"),
    top=Side(style="thin", color="B7C4D4"),
    bottom=Side(style="thin", color="B7C4D4"),
)

HEADER_ALIGNMENT = Alignment(vertical="top", wrap_text=True)
CELL_ALIGNMENT = Alignment(vertical="top")

EMPTY_TABLE_TEXT = "No data available for the selected filters."
SHEET_NAME_LIMIT = 31
MIN_COLUMN_WIDTH = 10
MAX_COLUMN_WIDTH = 60


def _unique_sheet_name(raw_name: str, used_names: set[str]) -> str:
    base = re.sub(r"[\\/*?:\[\]]", "-", raw_name).strip() or "Report"
    base = base[:SHEET_NAME_LIMIT]

    name = base
    suffix = 2

    while name.lower() in used_names:
        suffix_text = f"-{suffix}"
        name = f"{base[: SHEET_NAME_LIMIT - len(suffix_text)]}{suffix_text}"
        suffix += 1

    used_names.add(name.lower())

    return name


def _write_text(sheet: Worksheet, row: int, column: int, value, font: Font):
    cell = sheet.cell(row=row, column=column, value=value)
    cell.font = font

    return cell


def _write_data_cell(sheet: Worksheet, row: int, column: int, value) -> None:
    cell = sheet.cell(row=row, column=column)
    cell.alignment = CELL_ALIGNMENT

    if isinstance(value, str) and value.startswith("="):
        # Never let report data be interpreted as a spreadsheet formula.
        cell.value = value
        cell.data_type = "s"
        return

    cell.value = value


def _write_report_header(sheet: Worksheet, content: ReportContent, row: int) -> int:
    _write_text(sheet, row, 1, "PolicyGPT", TITLE_FONT)
    row += 1
    _write_text(sheet, row, 1, content.title, SUBTITLE_FONT)
    row += 2

    metadata = [
        ("Report Type", report_type_label(content.report_type)),
        ("Generated At", format_timestamp(content.generated_at)),
        ("Generated By", content.generated_by),
        ("Applied Filters", format_filters(content.filters)),
    ]

    for label, value in metadata:
        _write_text(sheet, row, 1, label, LABEL_FONT)
        sheet.cell(row=row, column=2, value=value)
        row += 1

    row += 1

    if content.summary:
        _write_text(sheet, row, 1, "Summary", SECTION_FONT)
        row += 1

        for item in content.summary:
            _write_text(sheet, row, 1, item.label, LABEL_FONT)
            sheet.cell(row=row, column=2, value=item.value)
            row += 1

        row += 1

    return row


def _column_widths(table: ReportTable) -> list[int]:
    widths: list[int] = []

    for index, column in enumerate(table.columns):
        longest = len(str(column))

        for row in table.rows:
            if index < len(row):
                value = row[index]
                longest = max(
                    longest,
                    len("" if value is None else str(value)),
                )

        widths.append(
            min(max(longest + 2, MIN_COLUMN_WIDTH), MAX_COLUMN_WIDTH)
        )

    return widths


def _merged_column_widths(tables: list[ReportTable]) -> list[int]:
    """Widest cell per column index across every table on the sheet.

    Several tables share one sheet but their columns do not line up, so each
    column takes the maximum width any table needs at that index — setting
    widths per table made the last table on the sheet win.
    """

    merged: list[int] = []

    for table in tables:
        for index, width in enumerate(_column_widths(table)):
            if index < len(merged):
                merged[index] = max(merged[index], width)
            else:
                merged.append(width)

    return merged


def _write_table(sheet: Worksheet, table: ReportTable, row: int, is_first: bool) -> int:
    if table.title:
        _write_text(sheet, row, 1, table.title, SECTION_FONT)
        row += 1

    header_row = row

    for index, column in enumerate(table.columns, start=1):
        cell = sheet.cell(row=row, column=index, value=column)
        cell.font = HEADER_FONT
        cell.fill = HEADER_FILL
        cell.alignment = HEADER_ALIGNMENT
        cell.border = THIN_BORDER

    row += 1

    if table.rows:
        for data_row in table.rows:
            for index, value in enumerate(data_row, start=1):
                _write_data_cell(sheet, row, index, value)
            row += 1
    else:
        sheet.cell(row=row, column=1, value=EMPTY_TABLE_TEXT)
        row += 1

    if is_first:
        sheet.freeze_panes = sheet.cell(row=header_row + 1, column=1)
        sheet.auto_filter.ref = (
            f"A{header_row}:"
            f"{get_column_letter(len(table.columns))}{header_row + len(table.rows)}"
        )

    return row + 1


def _write_section(sheet: Worksheet, section: ReportSection, row: int) -> int:
    for index, table in enumerate(section.tables):
        row = _write_table(sheet, table, row, is_first=index == 0)

    for index, width in enumerate(_merged_column_widths(section.tables), start=1):
        sheet.column_dimensions[get_column_letter(index)].width = width

    return row


def generate_excel_report(content: ReportContent, output_path: Path) -> None:
    workbook = Workbook()
    default_sheet = workbook.active
    used_names: set[str] = set()

    sections = content.sections

    if not sections:
        default_sheet.title = _unique_sheet_name(content.title, used_names)
        _write_report_header(default_sheet, content, 1)
    else:
        for index, section in enumerate(sections):
            sheet = default_sheet if index == 0 else workbook.create_sheet()
            sheet.title = _unique_sheet_name(section.title, used_names)

            row = _write_report_header(sheet, content, 1) if index == 0 else 1
            _write_section(sheet, section, row)

    workbook.save(str(output_path))
