logger = logging.getLogger(__name__)

# Deadline reminders are generated by an in-process sweep because the project
# has no task queue. The sweep is idempotent, so an interval and a short
# startup delay are enough — no external scheduler or worker is required.
DEADLINE_REMINDER_INTERVAL_HOURS = float(
    os.getenv("DEADLINE_REMINDER_INTERVAL_HOURS", "24")
)
DEADLINE_REMINDER_STARTUP_DELAY_SECONDS = float(
    os.getenv("DEADLINE_REMINDER_STARTUP_DELAY_SECONDS", "30")
)


def _run_deadline_reminder_sweep() -> None:
    db = SessionLocal()

    try:
        result = run_deadline_reminders(db)

        if result["reminders_created"]:
            logger.info("Deadline reminders created: %s", result)
    except Exception:
        db.rollback()
        logger.exception("Deadline reminder sweep failed")
    finally:
        db.close()


async def _deadline_reminder_loop() -> None:
    await asyncio.sleep(DEADLINE_REMINDER_STARTUP_DELAY_SECONDS)

    while True:
        # The sweep is blocking SQLAlchemy work, so it runs off the event loop.
        await asyncio.to_thread(_run_deadline_reminder_sweep)
        await asyncio.sleep(DEADLINE_REMINDER_INTERVAL_HOURS * 3600)


@asynccontextmanager
async def lifespan(app: FastAPI):
    task = asyncio.create_task(_deadline_reminder_loop())

    try:
        yield
    finally:
        task.cancel()

        try:
            await task
        except asyncio.CancelledError:
            pass


