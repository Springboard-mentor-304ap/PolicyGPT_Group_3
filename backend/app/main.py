logger = logging.getLogger(__name__)# Deadline reminders are generated by an in-process sweep because the project
# has no task queue. The sweep is idempotent, so an interval and a short
# startup delay are enough — no external scheduler or worker is required.
# The same loop also expires old generated report files, so both periodic
# maintenance jobs share one scheduler.
DEADLINE_REMINDER_INTERVAL_HOURS = float(
    os.getenv("DEADLINE_REMINDER_INTERVAL_HOURS", "24")
)
DEADLINE_REMINDER_STARTUP_DELAY_SECONDS = float(
    os.getenv("DEADLINE_REMINDER_STARTUP_DELAY_SECONDS", "30")
)

def _run_maintenance_sweep() -> None:
    db = SessionLocal()

    try:
        result = run_deadline_reminders(db)

        if result["reminders_created"]:
            logger.info("Deadline reminders created: %s", result)
    except Exception:
        db.rollback()
        logger.exception("Deadline reminder sweep failed")
    finally:
        db.close()

    db = SessionLocal()

    try:
        expired = cleanup_expired_reports(db)

        if expired:
            logger.info("Expired reports cleaned up: %s", expired)
    except Exception:
        db.rollback()
        logger.exception("Report cleanup sweep failed")
    finally:
        db.close()

    # Refresh-token rows whose token can no longer be used are deleted here
    # as well; revoked-but-unexpired rows are kept because they are what
    # detects a replay of a rotated token.
    db = SessionLocal()

    try:
        removed = cleanup_expired_refresh_tokens(db)

        if removed:
            logger.info("Expired refresh token rows cleaned up: %s", removed)
    except Exception:
        db.rollback()
        logger.exception("Refresh token cleanup sweep failed")
    finally:
        db.close()


async def _maintenance_loop() -> None:
    await asyncio.sleep(DEADLINE_REMINDER_STARTUP_DELAY_SECONDS)

    while True:
        # The sweep is blocking SQLAlchemy work, so it runs off the event loop.
        await asyncio.to_thread(_run_maintenance_sweep)
        await asyncio.sleep(DEADLINE_REMINDER_INTERVAL_HOURS * 3600)


@asynccontextmanager
async def lifespan(app: FastAPI):
    task = asyncio.create_task(_maintenance_loop())

    try:
        yield
    finally:
        task.cancel()

        try:
            await task
        except asyncio.CancelledError:
            pass

        shutdown_sync_executor()


app = FastAPI(lifespan=lifespan)

# Explicit origin list (never "*") with credentials enabled. The default
# covers both ways the Angular dev server reaches the API: the dev server
# itself (http://localhost:4200) and the same-origin proxy it forwards /api
# through (frontend/proxy.conf.json). Production overrides the variable with
# its real front-end origins, comma-separated.
CORS_ALLOWED_ORIGINS = [
    origin.strip()
    for origin in os.getenv(
        "CORS_ALLOWED_ORIGINS",
        "http://localhost:4200,http://localhost:8000",
    ).split(",")
    if origin.strip()
]

app.add_middleware(
    CORSMiddleware,
    allow_origins=CORS_ALLOWED_ORIGINS,
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

