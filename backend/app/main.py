@app.get("/health")
def health(db: Session = Depends(get_db)):
    """Liveness probe that also verifies the database is reachable."""

    try:
        db.execute(text("SELECT 1"))
    except Exception:
        raise HTTPException(
            status_code=503,
            detail="Database connection is not available",
        )

    return {"status": "ok", "database": "connected"}