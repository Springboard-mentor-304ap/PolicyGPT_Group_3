import { Injectable, inject } from '@angular/core';
import { HttpClient, HttpHeaders } from '@angular/common/http';
import { Observable } from 'rxjs';

import {
  Report,
  ReportGenerateRequest,
} from '../models/report.models';

@Injectable({ providedIn: 'root' })
export class ReportService {
  private readonly http = inject(HttpClient);

  private readonly ACCESS_TOKEN_KEY = 'policygpt_access_token';

  private getAuthHeaders(): HttpHeaders {
    const token = localStorage.getItem(this.ACCESS_TOKEN_KEY);
    return token
      ? new HttpHeaders({ Authorization: `Bearer ${token}` })
      : new HttpHeaders();
  }

  /** Generate a new PDF / Excel report (government officials and admins). */
  generateReport(data: ReportGenerateRequest): Observable<Report> {
    return this.http.post<Report>('/api/reports/generate', data, {
      headers: this.getAuthHeaders(),
    });
  }

  /** Reports generated by the current user (newest first). */
  listReports(): Observable<Report[]> {
    return this.http.get<Report[]>('/api/reports', {
      headers: this.getAuthHeaders(),
    });
  }

  /** Download a generated report file (PDF / Excel). */
  downloadReport(reportId: string): Observable<Blob> {
    return this.http.get(`/api/reports/${reportId}/download`, {
      headers: this.getAuthHeaders(),
      responseType: 'blob',
    });
  }
}
